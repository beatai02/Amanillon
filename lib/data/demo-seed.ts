function tradeFrom(partial: Omit<Trade, "plannedRr" | "actualRr" | "pnlGross" | "playbookSnapshot" | "createdAt" | "updatedAt" | "notes" | "images" | "review"> & { playbook: Playbook; notes?: string | null }): Trade {
  const metrics = computeTradeMetrics({
    entry: partial.entry,
    stopLoss: partial.stopLoss,
    takeProfit: partial.takeProfit,
    exitPrice: partial.exitPrice,
    direction: partial.direction,
    quantity: partial.quantity,
    contractSize: partial.contractSizeUsed ?? 1,
    fx: partial.fxRateUsed ?? 1,
  });
  const { playbook, ...rest } = partial;
  return {
    ...rest,
    playbookSnapshot: {
      id: playbook.id,
      name: playbook.name,
      approach: playbook.approach,
      tradingStyle: playbook.tradingStyle,
      setupTypes: playbook.setupTypes,
      confluences: playbook.confluences,
      htf: playbook.htf,
      intermediateTf: playbook.intermediateTf,
      entryTf: playbook.entryTf,
      checklist: playbook.checklist,
      entryCriteria: playbook.entryCriteria,
      exitCriteria: playbook.exitCriteria,
      slManagement: playbook.slManagement,
      riskPerTradePct: playbook.riskPerTradePct,
      avgPlannedRr: playbook.avgPlannedRr,
      plannedRPerYear: playbook.plannedRPerYear,
      prepStatus: playbook.prepStatus,
      usageStatus: playbook.usageStatus,
    },
    notes: rest.notes ?? null,
    plannedRr: metrics.plannedRr,
    actualRr: metrics.actualRr,
    pnlGross: metrics.pnlGross,
    createdAt: rest.openedAt,
    updatedAt: rest.closedAt ?? rest.openedAt,
  };
}

